package _05_for_loops._2_badgers;

public class BadgerProgram {
	public static void main(String[] args) {
		
		int lyrics = 0;
		int lyrics2 = 0;
		int snake = 0;
		
		for ( lyrics=0; lyrics <= 12; lyrics +=1 ) {
			System.out.print("Badgers");
		}
		
		System.out.println();
		
		for ( lyrics2=1; lyrics2 <= 2; lyrics2 +=1) {
			System.out.print("Mushroom");
		}
		
		
		
		
		for ( snake=1; snake <= 1; snake +=1) {
			System.out.println();
			System.out.print("A Snake!!!!");
		}
	
	}

}
